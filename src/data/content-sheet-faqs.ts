function normalizeSlug(slug: string): string {
  return slug.trim().replace(/^\/+|\/+$/g, "").toLowerCase();
}

function lookup(map: Record<string, ContentSheetFaq[]>, slug: string): ContentSheetFaq[] | undefined {
  const key = normalizeSlug(slug);
  return map[key] || map[key.replace(/^custom-/, "")] || map[`custom-${key}`];
}

export function getCategoryFaqs(slug: string): ContentSheetFaq[] | undefined {
  return lookup(CATEGORY_FAQS, slug);
}

export function getProductFaqs(slug: string): ContentSheetFaq[] | undefined {
  return lookup(PRODUCT_FAQS, slug);
}

export type PageFaq = {
  id: string;
  question: string;
  answer: string;
  display_order: number;
};

export function toPageFaqs(slug: string, items: ContentSheetFaq[] | undefined): PageFaq[] | undefined {
  if (!items?.length) return undefined;
  return items.map((faq, index) => ({
    id: `sheet-faq-${slug}-${index + 1}`,
    question: faq.question,
    answer: faq.answer,
    display_order: index + 1,
  }));
}
